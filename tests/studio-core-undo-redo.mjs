import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const source=await readFile(new URL('../APP-Applications/_shared/studio-v2/undo-redo.js',import.meta.url),'utf8');
const mod=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const {clearUndoRedo,pushUndoRedo,getUndoRedoState,undo,redo,configureUndoRedo,subscribeUndoRedo}=mod;
clearUndoRedo();
let value=0,notifications=0;
const unsubscribe=subscribeUndoRedo(()=>notifications++);
const op=(next,label)=>{const previous=value;value=next;pushUndoRedo({label,undo:()=>{value=previous},redo:()=>{value=next}})};
op(1,'first');op(2,'second');
assert.deepEqual([value,getUndoRedoState().undoDepth,getUndoRedoState().redoDepth],[2,2,0]);
assert.equal(await undo(),true);assert.equal(value,1);
assert.equal(await undo(),true);assert.equal(value,0);
assert.equal(await undo(),false);
assert.equal(await redo(),true);assert.equal(value,1);
op(9,'replace future');assert.equal(getUndoRedoState().canRedo,false);
clearUndoRedo();assert.equal(getUndoRedoState().undoDepth,0);
pushUndoRedo({label:'reject undo',undo:async()=>{throw Error('undo rejected')}});
await assert.rejects(undo(),/undo rejected/);
assert.deepEqual([getUndoRedoState().undoDepth,getUndoRedoState().redoDepth],[1,0]);
clearUndoRedo();
pushUndoRedo({label:'reject redo',undo:()=>{},redo:async()=>{throw Error('redo rejected')}});
await undo();await assert.rejects(redo(),/redo rejected/);
assert.deepEqual([getUndoRedoState().undoDepth,getUndoRedoState().redoDepth],[0,1]);
clearUndoRedo();
configureUndoRedo({maxItems:2});
op(1,'a');op(2,'b');op(3,'c');
assert.equal(getUndoRedoState().undoDepth,2);
configureUndoRedo({maxItems:200});
unsubscribe();
assert.ok(notifications>=10);
console.log(JSON.stringify({ok:true,component:'studio-core-undo-redo',tests:['undo','redo','redo-cleared-on-push','clear','undo-exception-rollback','redo-exception-rollback','stack-limit','notifications']}));
